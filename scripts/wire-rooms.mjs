// Registers bedroom/suite interior photos from assets/media/rooms into the app (generates roomInterior.generated.ts).
import { readdirSync, existsSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const DIR = join(ROOT, "assets/media/rooms");
const OUT = join(ROOT, "src/core/constants/roomInterior.generated.ts");
const SLUGS = ["classic-one-bedroom", "premier-one-bedroom", "grand-one-bedroom", "signature-corner-suite", "terrace-apartment"];

const files = existsSync(DIR) ? readdirSync(DIR) : [];
const found = [];
for (const slug of SLUGS) {
  const f = files.find((n) => new RegExp(`^${slug}\.(jpe?g|png|webp)$`, "i").test(n));
  if (f) found.push([slug, f]);
}
const unknown = files.filter((n) => !/\.md$/i.test(n) && !found.some(([, f]) => f === n));

const body = found.map(([slug, f]) => `  "${slug}": require("../../../assets/media/rooms/${f}") as ImageSource,`).join("\n");
writeFileSync(
  OUT,
  `// GENERATED by scripts/wire-rooms.mjs (npm run rooms) — do not edit by hand.\nimport type { ImageSource } from "expo-image";\n\nexport const ROOM_INTERIOR_GENERATED: Partial<Record<string, ImageSource>> = {\n${body}\n};\n`,
);
console.log(`Wired ${found.length}/${SLUGS.length} room interiors: ${found.map(([s]) => s).join(", ") || "none"}`);
if (unknown.length) console.warn(`Ignored (name must match a room type): ${unknown.join(", ")}`);
